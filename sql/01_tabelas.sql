-- SCC0640 - Sistema de Gestao de Eventos e Espacos
-- Fonte: docs/modelagem/Relacional.pdf e decisoes Q1-Q6 aprovadas.
-- Executar em uma base vazia. Nao apaga nem substitui estruturas existentes.
-- Funcoes e triggers de negocio serao definidos por Marcela em 02_triggers.sql.
BEGIN;

CREATE TABLE evento (
    id_evento integer GENERATED BY DEFAULT AS IDENTITY,
    nome varchar NOT NULL,
    descricao text,
    area varchar,
    CONSTRAINT pk_evento PRIMARY KEY (id_evento),
    CONSTRAINT ck_evento_nome CHECK (btrim(nome) <> '')
);

CREATE TABLE promotor (
    id_promotor integer GENERATED BY DEFAULT AS IDENTITY,
    nome varchar NOT NULL,
    tipo varchar NOT NULL,
    documento varchar NOT NULL,
    CONSTRAINT pk_promotor PRIMARY KEY (id_promotor),
    CONSTRAINT uq_promotor_documento UNIQUE (documento),
    CONSTRAINT ck_promotor_nome CHECK (btrim(nome) <> ''),
    CONSTRAINT ck_promotor_tipo CHECK (tipo IN ('PESSOA', 'ORGANIZACAO')),
    CONSTRAINT ck_promotor_documento CHECK (btrim(documento) <> '')
);

CREATE TABLE pessoa (
    id_pessoa integer GENERATED BY DEFAULT AS IDENTITY,
    nome varchar NOT NULL,
    email varchar NOT NULL,
    instituicao varchar,
    CONSTRAINT pk_pessoa PRIMARY KEY (id_pessoa),
    CONSTRAINT uq_pessoa_email UNIQUE (email),
    CONSTRAINT ck_pessoa_nome CHECK (btrim(nome) <> ''),
    CONSTRAINT ck_pessoa_email CHECK (btrim(email) <> '')
);

CREATE TABLE espaco (
    id_espaco integer GENERATED BY DEFAULT AS IDENTITY,
    nome varchar NOT NULL,
    tipo varchar NOT NULL,
    capacidade integer NOT NULL,
    predio varchar,
    CONSTRAINT pk_espaco PRIMARY KEY (id_espaco),
    CONSTRAINT ck_espaco_nome CHECK (btrim(nome) <> ''),
    CONSTRAINT ck_espaco_tipo CHECK (btrim(tipo) <> ''),
    CONSTRAINT ck_espaco_capacidade CHECK (capacidade > 0)
);

CREATE TABLE recurso (
    id_recurso integer GENERATED BY DEFAULT AS IDENTITY,
    nome varchar NOT NULL,
    CONSTRAINT pk_recurso PRIMARY KEY (id_recurso),
    CONSTRAINT uq_recurso_nome UNIQUE (nome),
    CONSTRAINT ck_recurso_nome CHECK (btrim(nome) <> '')
);

CREATE TABLE edicao (
    id_edicao integer GENERATED BY DEFAULT AS IDENTITY,
    id_evento integer NOT NULL,
    ano integer NOT NULL,
    data_inicio date NOT NULL,
    data_fim date NOT NULL,
    cidade varchar,
    status varchar NOT NULL DEFAULT 'PLANEJADA',
    CONSTRAINT pk_edicao PRIMARY KEY (id_edicao),
    CONSTRAINT fk_edicao_evento FOREIGN KEY (id_evento) REFERENCES evento (id_evento)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT uq_edicao_evento_ano UNIQUE (id_evento, ano),
    CONSTRAINT ck_edicao_ano CHECK (ano > 0),
    CONSTRAINT ck_edicao_periodo CHECK (
        isfinite(data_inicio) AND isfinite(data_fim) AND data_fim >= data_inicio
    ),
    CONSTRAINT ck_edicao_status CHECK (
        status IN ('PLANEJADA', 'EM_ANDAMENTO', 'ENCERRADA', 'CANCELADA')
    )
);

CREATE TABLE atividade (
    id_atividade integer GENERATED BY DEFAULT AS IDENTITY,
    id_edicao integer NOT NULL,
    titulo varchar NOT NULL,
    descricao text,
    tipo varchar NOT NULL,
    carga_horaria integer,
    CONSTRAINT pk_atividade PRIMARY KEY (id_atividade),
    CONSTRAINT fk_atividade_edicao FOREIGN KEY (id_edicao) REFERENCES edicao (id_edicao)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_atividade_titulo CHECK (btrim(titulo) <> ''),
    CONSTRAINT ck_atividade_tipo CHECK (btrim(tipo) <> ''),
    CONSTRAINT ck_atividade_carga_horaria CHECK (carga_horaria > 0)
);

CREATE TABLE sessao (
    id_sessao integer GENERATED BY DEFAULT AS IDENTITY,
    id_atividade integer NOT NULL,
    id_espaco integer NOT NULL,
    data date NOT NULL,
    hora_inicio time NOT NULL,
    hora_fim time NOT NULL,
    vagas_limite integer,
    status varchar NOT NULL DEFAULT 'AGENDADA',
    duracao_min integer GENERATED ALWAYS AS (
        floor(extract(epoch FROM (hora_fim - hora_inicio)) / 60)::integer
    ) STORED,
    CONSTRAINT pk_sessao PRIMARY KEY (id_sessao),
    CONSTRAINT fk_sessao_atividade FOREIGN KEY (id_atividade) REFERENCES atividade (id_atividade)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_sessao_espaco FOREIGN KEY (id_espaco) REFERENCES espaco (id_espaco)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_sessao_data CHECK (isfinite(data)),
    CONSTRAINT ck_sessao_horario CHECK (hora_fim > hora_inicio),
    CONSTRAINT ck_sessao_vagas_limite CHECK (vagas_limite > 0),
    CONSTRAINT ck_sessao_status CHECK (status IN ('AGENDADA', 'REALIZADA', 'CANCELADA'))
);

CREATE TABLE historico_sessao (
    id_historico integer GENERATED BY DEFAULT AS IDENTITY,
    id_sessao integer NOT NULL,
    espaco_anterior varchar NOT NULL,
    data_anterior date NOT NULL,
    hora_inicio_anterior time NOT NULL,
    hora_fim_anterior time NOT NULL,
    alterado_em timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo text,
    CONSTRAINT pk_historico_sessao PRIMARY KEY (id_historico),
    CONSTRAINT fk_historico_sessao_sessao FOREIGN KEY (id_sessao) REFERENCES sessao (id_sessao)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_historico_sessao_espaco CHECK (btrim(espaco_anterior) <> ''),
    CONSTRAINT ck_historico_sessao_data CHECK (isfinite(data_anterior)),
    CONSTRAINT ck_historico_sessao_horario CHECK (hora_fim_anterior > hora_inicio_anterior),
    CONSTRAINT ck_historico_sessao_alterado_em CHECK (isfinite(alterado_em))
);

CREATE TABLE edicao_promotor (
    id_edicao integer NOT NULL,
    id_promotor integer NOT NULL,
    papel varchar NOT NULL,
    CONSTRAINT pk_edicao_promotor PRIMARY KEY (id_edicao, id_promotor),
    CONSTRAINT fk_edicao_promotor_edicao FOREIGN KEY (id_edicao) REFERENCES edicao (id_edicao)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_edicao_promotor_promotor FOREIGN KEY (id_promotor) REFERENCES promotor (id_promotor)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_edicao_promotor_papel CHECK (papel IN ('principal', 'co-promotor'))
);

CREATE TABLE inscricao_edicao (
    id_pessoa integer NOT NULL,
    id_edicao integer NOT NULL,
    data_inscricao timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status varchar NOT NULL DEFAULT 'CONFIRMADA',
    CONSTRAINT pk_inscricao_edicao PRIMARY KEY (id_pessoa, id_edicao),
    CONSTRAINT fk_inscricao_edicao_pessoa FOREIGN KEY (id_pessoa) REFERENCES pessoa (id_pessoa)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_inscricao_edicao_edicao FOREIGN KEY (id_edicao) REFERENCES edicao (id_edicao)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_inscricao_edicao_data CHECK (isfinite(data_inscricao)),
    CONSTRAINT ck_inscricao_edicao_status CHECK (status IN ('CONFIRMADA', 'CANCELADA'))
);

CREATE TABLE equipe_edicao (
    id_pessoa integer NOT NULL,
    id_edicao integer NOT NULL,
    papel varchar NOT NULL,
    CONSTRAINT pk_equipe_edicao PRIMARY KEY (id_pessoa, id_edicao),
    CONSTRAINT fk_equipe_edicao_pessoa FOREIGN KEY (id_pessoa) REFERENCES pessoa (id_pessoa)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_equipe_edicao_edicao FOREIGN KEY (id_edicao) REFERENCES edicao (id_edicao)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_equipe_edicao_papel CHECK (papel IN ('organizador', 'voluntario'))
);

CREATE TABLE espaco_recurso (
    id_espaco integer NOT NULL,
    id_recurso integer NOT NULL,
    quantidade integer NOT NULL,
    CONSTRAINT pk_espaco_recurso PRIMARY KEY (id_espaco, id_recurso),
    CONSTRAINT fk_espaco_recurso_espaco FOREIGN KEY (id_espaco) REFERENCES espaco (id_espaco)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_espaco_recurso_recurso FOREIGN KEY (id_recurso) REFERENCES recurso (id_recurso)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_espaco_recurso_quantidade CHECK (quantidade > 0)
);

CREATE TABLE atividade_pessoa (
    id_atividade integer NOT NULL,
    id_pessoa integer NOT NULL,
    papel varchar NOT NULL,
    CONSTRAINT pk_atividade_pessoa PRIMARY KEY (id_atividade, id_pessoa),
    CONSTRAINT fk_atividade_pessoa_atividade FOREIGN KEY (id_atividade) REFERENCES atividade (id_atividade)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_atividade_pessoa_pessoa FOREIGN KEY (id_pessoa) REFERENCES pessoa (id_pessoa)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_atividade_pessoa_papel CHECK (papel IN ('palestrante', 'instrutor', 'mediador'))
);

CREATE TABLE atividade_recurso (
    id_atividade integer NOT NULL,
    id_recurso integer NOT NULL,
    quantidade_minima integer NOT NULL,
    CONSTRAINT pk_atividade_recurso PRIMARY KEY (id_atividade, id_recurso),
    CONSTRAINT fk_atividade_recurso_atividade FOREIGN KEY (id_atividade) REFERENCES atividade (id_atividade)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_atividade_recurso_recurso FOREIGN KEY (id_recurso) REFERENCES recurso (id_recurso)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_atividade_recurso_quantidade CHECK (quantidade_minima > 0)
);

CREATE TABLE inscricao_sessao (
    id_sessao integer NOT NULL,
    id_pessoa integer NOT NULL,
    data_inscricao timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status varchar NOT NULL DEFAULT 'CONFIRMADA',
    posicao_espera integer,
    CONSTRAINT pk_inscricao_sessao PRIMARY KEY (id_sessao, id_pessoa),
    CONSTRAINT fk_inscricao_sessao_sessao FOREIGN KEY (id_sessao) REFERENCES sessao (id_sessao)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_inscricao_sessao_pessoa FOREIGN KEY (id_pessoa) REFERENCES pessoa (id_pessoa)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_inscricao_sessao_data CHECK (isfinite(data_inscricao)),
    CONSTRAINT ck_inscricao_sessao_status CHECK (
        status IN ('CONFIRMADA', 'LISTA_ESPERA', 'CANCELADA')
    ),
    CONSTRAINT ck_inscricao_sessao_espera CHECK (
        (status = 'LISTA_ESPERA' AND posicao_espera IS NOT NULL AND posicao_espera > 0)
        OR (status IN ('CONFIRMADA', 'CANCELADA') AND posicao_espera IS NULL)
    ),
    -- Adiavel para permitir reordenar a fila na mesma transacao.
    CONSTRAINT uq_inscricao_sessao_posicao UNIQUE (id_sessao, posicao_espera)
        DEFERRABLE INITIALLY IMMEDIATE
);

-- Cobertura das FKs nao cobertas pelo prefixo de uma PK/UNIQUE.
CREATE INDEX ix_atividade_edicao ON atividade (id_edicao);
CREATE INDEX ix_sessao_atividade ON sessao (id_atividade);
CREATE INDEX ix_sessao_espaco_programacao ON sessao (id_espaco, data, hora_inicio);
CREATE INDEX ix_historico_sessao_sessao ON historico_sessao (id_sessao, alterado_em);
CREATE INDEX ix_edicao_promotor_promotor ON edicao_promotor (id_promotor);
CREATE INDEX ix_inscricao_edicao_edicao ON inscricao_edicao (id_edicao);
CREATE INDEX ix_equipe_edicao_edicao ON equipe_edicao (id_edicao);
CREATE INDEX ix_espaco_recurso_recurso ON espaco_recurso (id_recurso);
CREATE INDEX ix_atividade_pessoa_pessoa ON atividade_pessoa (id_pessoa);
CREATE INDEX ix_atividade_recurso_recurso ON atividade_recurso (id_recurso);
CREATE INDEX ix_inscricao_sessao_pessoa ON inscricao_sessao (id_pessoa);
CREATE INDEX ix_inscricao_sessao_status ON inscricao_sessao (id_sessao, status);

COMMENT ON COLUMN sessao.vagas_limite IS
    'NULL: sem limite proprio de inscricao; capacidade efetiva de sessoes com inscricao = LEAST(vagas_limite, espaco.capacidade). Controle por trigger.';
COMMENT ON COLUMN sessao.duracao_min IS
    'Minutos completos entre hora_inicio e hora_fim; calculado pelo PostgreSQL, nao informar no INSERT/UPDATE.';
COMMENT ON COLUMN historico_sessao.espaco_anterior IS
    'Snapshot textual do espaco anterior, conforme varchar do modelo; trigger deve registrar OLD.id_espaco::varchar para preservar a identidade sem nova FK.';
COMMENT ON TABLE inscricao_sessao IS
    'Independente de inscricao_edicao (Q5); nao existe FK nem pre-requisito de inscricao na edicao. Lotacao e promocao de fila dependem de triggers.';

COMMIT;
